"""TBDub Student lipsync backend (in-process).

Replaces LatentSync as the mouth generator while keeping the V2 speaking /
face / shot gates untouched: contiguous speaking runs are generated by TBDub's
Student DiT and mapped back as full frames.

Why in-process and why no MediaPipe:
- TBDub's own MediaPipe preprocessor is a single-face tracker; on multi-person /
  profile / shot-cut material it misses ~72% of landmarks and raises on gaps
  longer than 10 frames. This backend skips MediaPipe entirely and feeds
  MuseTalk's primary-face ``coord_list`` boxes into TBDub's own
  ``process_bbox -> crop_and_resize_frames`` alignment (a plain square crop,
  not an arcface affine - see ``tbdub_square_boxes``, which restores the square
  convention that alignment assumes before our tall DWPose boxes reach it),
  then pastes back with TBDub's
  ``blend_crop_video_with_ref -> paste_video_back``.
- TBDub is hardwired to 25fps (audio->frame addressing, 77-frame clips), so
  each speaking run is resampled src-fps -> 25 fps here, generated, and
  re-timed back onto the source timeline; the rest of the pipeline stays on
  the source fps and all gating thresholds keep their tuned values.

Contract is identical to LatentSyncBackend.lipsync_indices: returns
``{frame index: full BGR frame}``, so the engine's paste / color-match /
streaming composite path is unchanged.
"""

from __future__ import annotations

import logging
import os
import sys
import time
from types import SimpleNamespace
from typing import Callable, Dict, List, Optional, Sequence

import cv2
import numpy as np
import torch
from PIL import Image

from musetalk.service.latentsync_backend import cleanup_runs, contiguous_runs
from musetalk.service.long_video import split_audio_segment_frames

logger = logging.getLogger("musetalk_service")

_REPO_DEFAULT = os.path.abspath(
    os.path.join(os.path.dirname(__file__), "..", "..", "third_party", "TBDub")
)

# VRAM knob shared with LatentSyncBackend: hand caching-allocator segments back
# to the driver after each run (this is a shared/multi-tenant GPU).
_EMPTY_CACHE_ENV = "MUSETALK_TBDUB_EMPTY_CACHE"


def _bgr_to_pil(frame: np.ndarray) -> Image.Image:
    return Image.fromarray(cv2.cvtColor(frame, cv2.COLOR_BGR2RGB)).convert("RGB")


def _resample_indices(n_src: int, n_dst: int) -> List[int]:
    """Nearest-source-frame index map for a linear src->dst fps resample."""
    if n_src <= 0 or n_dst <= 0:
        return []
    if n_dst == 1:
        return [n_src // 2]
    return [
        min(n_src - 1, max(0, int(round(k * (n_src - 1) / (n_dst - 1)))))
        for k in range(n_dst)
    ]


# TBDub's crop alignment is built around SQUARE face boxes: its own MediaPipe
# stage (preprocessing.build_face_bbox_from_landmarks) takes
# ``max(w, h) * 1.45`` centered on the face. MuseTalk's primary boxes come from
# DWPose and are TALL (h ~ 1.5 w, brows..chin). process_bbox then squares them
# with ``side = min(x2 - x1, y2 - y1)`` anchored at the TOP-LEFT corner
# (preprocessing.get_smooth_bbox), so a tall box keeps only its upper strip -
# forehead and eyes - and the mouth falls outside the crop handed to the model.
# Measured on a real 12s clip: 247/247 detected frames had the mouth cut off.
# Restore the square, centered convention here, and keep the tight mouth box
# inside with a chin margin so the generator can never be fed a mouthless crop.
TBDUB_BBOX_MARGIN = 1.45


def tbdub_square_boxes(
    boxes: Sequence[Optional[Sequence[float]]],
    mouth_boxes: Optional[Sequence[Optional[Sequence[float]]]] = None,
    width: int = 0,
    height: int = 0,
) -> List[List[float]]:
    """Convert primary face boxes to TBDub's square, centered crop geometry."""
    out: List[List[float]] = []
    for i, box in enumerate(boxes):
        valid = (
            box is not None
            and len(box) >= 4
            and float(box[2]) > float(box[0])
            and float(box[3]) > float(box[1])
        )
        if not valid:
            out.append([0.0, 0.0, float(width), float(height)])
            continue
        x1, y1, x2, y2 = (float(v) for v in box[:4])
        cx, cy = (x1 + x2) / 2.0, (y1 + y2) / 2.0
        side = max(x2 - x1, y2 - y1) * TBDUB_BBOX_MARGIN

        mb = mouth_boxes[i] if mouth_boxes is not None and i < len(mouth_boxes) else None
        if (
            mb is not None
            and len(mb) >= 4
            and float(mb[2]) > float(mb[0])
            and float(mb[3]) > float(mb[1])
        ):
            mx1, my1, mx2, my2 = (float(v) for v in mb[:4])
            pad = 0.25 * max(mx2 - mx1, my2 - my1)
            # the box stays centered on the face, so the side has to reach the
            # farthest padded mouth edge measured from that center
            side = max(
                side,
                2.0 * max(abs((mx2 + pad) - cx), abs((mx1 - pad) - cx)),
                2.0 * max(abs((my2 + pad) - cy), abs((my1 - pad) - cy)),
            )
        side = min(side, float(width), float(height))
        bx1 = min(max(0.0, cx - side / 2.0), float(width) - side)
        by1 = min(max(0.0, cy - side / 2.0), float(height) - side)
        out.append([bx1, by1, bx1 + side, by1 + side])
    return out


def per_shot_process_bbox(
    bbox_list: Sequence[Sequence[float]],
    shot_ids: Optional[Sequence[int]],
    width: int,
    height: int,
    process_bbox,
) -> List[List[float]]:
    """Run TBDub's bbox smoothing once per shot instead of once per run.

    ``get_smooth_bbox`` filters with a 25-frame Savitzky-Golay window over the
    whole list, so a hard cut lets the neighbouring shot drag the anchor and the
    crop lands on the forehead of the next face. Grouping by shot id keeps the
    smoothing inside one continuous take.
    """
    n = len(bbox_list)
    if not shot_ids or len(shot_ids) != n:
        smoothed, flag = process_bbox([list(b) for b in bbox_list], width, height)
        return smoothed
    out: List[List[float]] = [None] * n  # type: ignore[list-item]
    start = 0
    flags = []
    for k in range(1, n + 1):
        if k == n or shot_ids[k] != shot_ids[start]:
            sub, flag = process_bbox([list(b) for b in bbox_list[start:k]], width, height)
            flags.append(int(flag))
            for j, b in enumerate(sub):
                out[start + j] = b
            start = k
    logger.debug("TBDub per-shot bbox: %d shot(s), modes=%s", len(flags), sorted(set(flags)))
    return out


class TBDubBackend:
    """Load TBDub Student once (lazy) and lipsync speaking runs in-process.

    The crop geometry is the whole story here: TBDub squares whatever face box it is
    given, so the tall DWPose boxes have to be converted first (``tbdub_square_boxes``)
    or the mouth leaves the crop and the model has nothing to follow.
    """

    # the crop geometry has to be told where the mouth is (see tbdub_square_boxes)
    supports_mouth_boxes = True

    _crop_dump_index = 0

    def __init__(
        self,
        *,
        device: torch.device,
        repo_root: str = _REPO_DEFAULT,
        checkpoint_dir: str = "",
        num_student_steps: int = 2,
        sigma_shift: float = 1.0,
        seed: int = 42,
        motion_from_latents: bool = True,
        cpu_offload: bool = True,
        ref_cfg_scale: float = 2.0,
        audio_cfg_scale: float = 6.0,
        target_fps: float = 25.0,
        min_run_frames: int = 8,
        merge_gap_frames: int = 4,
    ):
        self.device = device
        self.repo_root = os.path.abspath(repo_root)
        self.checkpoint_dir = (
            os.path.abspath(checkpoint_dir)
            if checkpoint_dir
            else os.path.join(self.repo_root, "checkpoints")
        )
        self.num_student_steps = int(num_student_steps)
        self.sigma_shift = float(sigma_shift)
        self.seed = int(seed)
        self.motion_from_latents = bool(motion_from_latents)
        self.cpu_offload = bool(cpu_offload)
        self.ref_cfg_scale = float(ref_cfg_scale)
        self.audio_cfg_scale = float(audio_cfg_scale)
        # TBDub-native generation fps; all internal clip/audio addressing uses it.
        self.target_fps = float(target_fps) if target_fps and target_fps > 0 else 25.0
        # Run-layout knobs (same purpose as the LatentSync ones). Per-run fixed
        # overhead is even larger here: every clip re-warms the motion latents
        # and the HuBERT stream, so short fragments are disproportionately
        # expensive. Env kill-switches mirror the LatentSync ones.
        self.min_run_frames = int(
            os.environ.get("MUSETALK_TBDUB_MIN_RUN_FRAMES", str(min_run_frames)) or 0
        )
        self.merge_gap_frames = int(
            os.environ.get("MUSETALK_TBDUB_MERGE_GAP_FRAMES", str(merge_gap_frames)) or 0
        )
        self._pipeline = None
        self._prompt_embedding = None
        self._clip_frames = None
        if not os.path.isdir(self.repo_root):
            raise FileNotFoundError(f"TBDub repo not found: {self.repo_root}")
        # `preprocessing` / `video_utils` / `inference` live at the repo root.
        if self.repo_root not in sys.path:
            sys.path.insert(0, self.repo_root)

    # ------------------------------------------------------------------
    # Model loading (lazy: keep engine construction cheap; weights land on
    # first lipsync call).
    # ------------------------------------------------------------------

    def _ensure_loaded(self) -> None:
        if self._pipeline is not None:
            return
        _t0 = time.perf_counter()
        from diffsynth.pipelines.tbdub import TBDubPipeline
        from diffsynth.core import ModelConfig
        from inference import (  # noqa: E402  (TBDub repo is on sys.path)
            CLIP_NUM_FRAMES,
            MOTION_LATENT_NUM_FRAMES,
            MOTION_NUM_FRAMES,
        )

        dit = os.path.join(self.checkpoint_dir, "tbdub_student.safetensors")
        vae = os.path.join(self.checkpoint_dir, "Wan2.2_VAE.safetensors")
        prompt_emb_path = os.path.join(self.checkpoint_dir, "null_prompt_emb.pt")
        hubert_dir = os.path.join(self.checkpoint_dir, "hubert-large-ll60k")
        missing = [
            path
            for path in (dit, vae, prompt_emb_path, hubert_dir)
            if not os.path.exists(path)
        ]
        if missing:
            raise FileNotFoundError(
                "TBDub checkpoints missing: " + ", ".join(missing)
            )

        device_str = str(self.device)
        # Mirrors inference.py VRAM_CONFIG: everything computes in bf16 on the
        # GPU; cpu_offload parks the (large) DiT weights in host RAM between
        # uses so the engine's own models can stay resident on a shared GPU.
        vram = dict(
            offload_dtype=torch.bfloat16,
            offload_device="cpu" if self.cpu_offload else device_str,
            onload_dtype=torch.bfloat16,
            onload_device=device_str,
            preparing_dtype=torch.bfloat16,
            preparing_device=device_str,
            computation_dtype=torch.bfloat16,
            computation_device=device_str,
        )
        # Field set consumed by diffsynth + our clip loop; mirrors the
        # argparse.Namespace that inference.py builds (diffsynth itself only
        # reads args.num_frames / args.audio_feat_window_size).
        args = SimpleNamespace(
            inference_mode="student",
            num_inference_steps=30,  # teacher-only knob; unused for student
            num_student_steps=self.num_student_steps,
            sigma_shift=self.sigma_shift,
            seed=self.seed,
            per_chunk_audio=False,
            motion_from_latents=self.motion_from_latents,
            student_first_clip_padding=True,
            ref_cfg_scale=self.ref_cfg_scale,
            audio_cfg_scale=self.audio_cfg_scale,
            audio_feat_window_size=0,
            num_frames=CLIP_NUM_FRAMES,
            cpu_offload=self.cpu_offload,
            device=device_str,
        )
        logger.info(
            "Loading TBDub Student (dit=%s, steps=%d, cpu_offload=%s) on %s",
            os.path.basename(dit),
            self.num_student_steps,
            self.cpu_offload,
            device_str,
        )
        self._pipeline = TBDubPipeline.from_pretrained(
            torch_dtype=torch.bfloat16,
            device=device_str,
            model_configs=[
                ModelConfig(path=dit, **vram),
                ModelConfig(path=vae, **vram),
            ],
            args=args,
            hubert_ckpt_path=hubert_dir,
        )
        self._pipeline.hubert_processor.to(dtype=torch.float32)
        self._prompt_embedding = torch.load(
            prompt_emb_path, map_location=device_str, weights_only=True
        )
        self._clip_frames = (
            CLIP_NUM_FRAMES,
            MOTION_NUM_FRAMES,
            MOTION_LATENT_NUM_FRAMES,
        )
        logger.info("[timing] tbdub student load: %.3fs", time.perf_counter() - _t0)

    # ------------------------------------------------------------------
    # Public seam (identical signature to LatentSyncBackend.lipsync_indices)
    # ------------------------------------------------------------------

    def lipsync_indices(
        self,
        frame_list: List[np.ndarray],
        audio_path: str,
        infer_indices: Sequence[int],
        fps: float,
        temp_dir: str,
        coord_list: Optional[Sequence] = None,
        primary_iou_min: float = 0.3,  # unused; kept for seam compatibility
        mouth_boxes: Optional[Sequence] = None,
        stream_cb: Optional[Callable[[int, int, Dict[int, np.ndarray]], None]] = None,
    ) -> Dict[int, np.ndarray]:
        """Run TBDub on contiguous speaking runs; return full BGR frames.

        ``primary_iou_min`` is accepted but ignored: TBDub is driven directly by
        MuseTalk's primary-face ``coord_list`` (no second face detector), so the
        InsightFace pre-filter LatentSync needs does not apply here.
        """
        from musetalk.utils.preprocessing import coord_placeholder

        _t_filter = time.perf_counter()
        ordered = sorted(int(i) for i in infer_indices)
        faced_indices = [
            i
            for i in ordered
            if 0 <= i < len(frame_list)
            and coord_list is not None
            and i < len(coord_list)
            and coord_list[i] is not None
            and coord_list[i] != coord_placeholder
        ]
        if len(faced_indices) != len(ordered):
            logger.info(
                "TBDub coord pre-filter: keep %d/%d speaking frames (invalid primary box)",
                len(faced_indices),
                len(ordered),
            )
        logger.info(
            "[timing] tbdub coord pre-filter: %.3fs", time.perf_counter() - _t_filter
        )

        runs = contiguous_runs(faced_indices)
        _raw_frames = sum(e - s + 1 for s, e in runs)
        _n_raw = len(runs)
        shot_ids: Optional[List[int]] = None
        if self.merge_gap_frames > 0 and len(runs) > 1:
            try:
                from musetalk.utils.active_speaker import detect_shot_ids

                shot_ids = detect_shot_ids(frame_list)
            except Exception as exc:  # pragma: no cover - defensive
                logger.warning("TBDub merge shot-gate unavailable (%s); using bbox", exc)
                shot_ids = None
        runs = cleanup_runs(
            runs,
            min_run_frames=self.min_run_frames,
            merge_gap_frames=self.merge_gap_frames,
            coord_list=coord_list,
            shot_ids=shot_ids,
            merge_iou_min=0.5,
        )
        _kept_frames = sum(e - s + 1 for s, e in runs)
        if _kept_frames != _raw_frames or len(runs) != _n_raw:
            logger.info(
                "TBDub run cleanup: %d run(s)/%d frames -> %d run(s)/%d frames "
                "(min_run=%d merge_gap=%d)",
                _n_raw,
                _raw_frames,
                len(runs),
                _kept_frames,
                self.min_run_frames,
                self.merge_gap_frames,
            )
        if not runs:
            if infer_indices:
                logger.warning(
                    "TBDub: all %d speaking frames lack a valid primary face; "
                    "keeping originals",
                    len(ordered),
                )
            return {}

        fps = float(fps) if fps and fps > 0 else 25.0
        os.makedirs(temp_dir, exist_ok=True)
        out: Dict[int, np.ndarray] = {}
        infer_sec = 0.0
        logger.info(
            "TBDub: %d speaking frames (%d after coord filter) in %d contiguous run(s)",
            len(ordered),
            len(faced_indices),
            len(runs),
        )

        for run_i, (start, end) in enumerate(runs):
            n = end - start + 1
            run_audio = os.path.join(temp_dir, f"tbdub_run_{run_i:04d}.wav")
            _t_io = time.perf_counter()
            split_audio_segment_frames(
                audio_path,
                start_frame=start,
                frame_count=n,
                fps=fps,
                output_path=run_audio,
                sample_rate=16000,
            )
            logger.info(
                "TBDub run %d/%d: frames [%d, %d] (%d @ %.3ffps)",
                run_i + 1,
                len(runs),
                start,
                end,
                n,
                fps,
            )
            _t_inf = time.perf_counter()
            try:
                run_boxes = [
                    coord_list[i] if i < len(coord_list) else None
                    for i in range(start, end + 1)
                ]
                run_frames = self._infer_run(
                    frame_list[start : end + 1],
                    run_boxes,
                    run_audio,
                    fps=fps,
                    mouth_boxes=[
                        mouth_boxes[i] if mouth_boxes is not None and i < len(mouth_boxes) else None
                        for i in range(start, end + 1)
                    ],
                )
            except Exception:
                logger.exception(
                    "TBDub inference failed for run [%d, %d]; keeping originals",
                    start,
                    end,
                )
                run_frames = []
            infer_sec += time.perf_counter() - _t_inf
            if not run_frames:
                continue

            use_n = min(n, len(run_frames))
            if len(run_frames) != n:
                logger.warning(
                    "TBDub run [%d, %d] returned %d frames (expected %d); using %d",
                    start,
                    end,
                    len(run_frames),
                    n,
                    use_n,
                )
            mapped: Dict[int, np.ndarray] = {}
            for offset in range(use_n):
                mapped[start + offset] = run_frames[offset]
            out.update(mapped)
            if stream_cb is not None:
                stream_cb(start, end, mapped)

        logger.info(
            "[timing] tbdub summary: pipeline_infer=%.2fs (runs=%d, sync_frames=%d)",
            infer_sec,
            len(runs),
            len(out),
        )
        if (
            os.environ.get(_EMPTY_CACHE_ENV, "1") != "0"
            and torch.cuda.is_available()
        ):
            torch.cuda.empty_cache()
        return out

    # ------------------------------------------------------------------
    # Per-run generation (bounded port of TBDub inference.run_inference)
    # ------------------------------------------------------------------

    def _infer_run(
        self,
        frames_bgr: List[np.ndarray],
        boxes: List[Optional[Sequence[float]]],
        audio_path: str,
        fps: float,
        mouth_boxes: Optional[Sequence[Optional[Sequence[float]]]] = None,
    ) -> List[np.ndarray]:
        """Generate one speaking run; return full BGR frames on the src timeline.

        ``mouth_boxes`` are the tight DWPose lip boxes of the same run-local frames;
        they only have to be inside the crop, and they keep it honest (see
        ``tbdub_square_boxes``).
        """
        from preprocessing import crop_and_resize_frames, process_bbox  # TBDub repo
        from video_utils import (
            blend_crop_video_with_ref,
            color_correction_lab,
            get_audio_length,
            get_total_length,
            make_pingpong_indices,
            paste_video_back,
        )

        self._ensure_loaded()
        clip_num, motion_num, motion_latent_num = self._clip_frames
        h, w = frames_bgr[0].shape[:2]
        n_src = len(frames_bgr)

        # ---- src fps -> TBDub-native fps --------------------------------
        n_dst = max(1, int(round(n_src / fps * self.target_fps)))
        idx = _resample_indices(n_src, n_dst)
        raw_video = [_bgr_to_pil(frames_bgr[i]) for i in idx]
        # Invalid boxes (placeholder / degenerate) repeat the nearest valid
        # neighbour so the crop geometry never sees an empty hint.
        src_boxes: List[Optional[List[float]]] = []
        src_mouth: List[Optional[List[float]]] = []
        last_valid: Optional[List[float]] = None
        for i in idx:
            box = boxes[i] if boxes is not None and i < len(boxes) else None
            if (
                box is not None
                and len(box) >= 4
                and float(box[2]) > float(box[0])
                and float(box[3]) > float(box[1])
            ):
                last_valid = [float(v) for v in box[:4]]
            src_boxes.append(last_valid)
            # a stale mouth box would be worse than none, so no hold here
            mb = mouth_boxes[i] if mouth_boxes is not None and i < len(mouth_boxes) else None
            src_mouth.append(
                [float(v) for v in mb[:4]]
                if mb is not None
                and len(mb) >= 4
                and float(mb[2]) > float(mb[0])
                and float(mb[3]) > float(mb[1])
                else None
            )
        for i in range(len(src_boxes) - 1, -1, -1):
            if src_boxes[i] is None:
                src_boxes[i] = last_valid
            else:
                last_valid = src_boxes[i]
        if last_valid is None:
            raise ValueError("run has no valid primary face box")

        # TBDub squares what it is given (min side, top-left anchor), so hand it a
        # box that is already square and centered on the whole face.
        square_boxes = tbdub_square_boxes(src_boxes, src_mouth, w, h)
        run_shot_ids: Optional[List[int]] = None
        try:
            from musetalk.utils.active_speaker import detect_shot_ids

            _src_shots = detect_shot_ids(frames_bgr)
            run_shot_ids = [_src_shots[i] for i in idx]
        except Exception as exc:  # pragma: no cover - defensive
            logger.warning("TBDub per-shot bbox unavailable (%s); smoothing whole run", exc)
        bbox_list = per_shot_process_bbox(square_boxes, run_shot_ids, w, h, process_bbox)
        # never trust the smoothing: a crop without the mouth is what made the
        # generator ignore the audio, so report it instead of discovering it later
        cut = sum(
            1
            for mb, bb in zip(src_mouth, bbox_list)
            if mb is not None
            and (mb[3] > bb[3] or mb[1] < bb[1] or mb[2] > bb[2] or mb[0] < bb[0])
        )
        n_mouth = sum(1 for mb in src_mouth if mb is not None)
        if cut:
            logger.warning(
                "TBDub crop: mouth outside the crop in %d/%d frames", cut, n_mouth
            )
        reference_video = crop_and_resize_frames(raw_video, bbox_list)
        logger.info(
            "TBDub crop: src=%.3ffps(%d) -> %.0ffps(%d), shots=%d, mouth_in_crop=%d/%d, "
            "first_bbox=%s",
            fps,
            n_src,
            self.target_fps,
            n_dst,
            len(set(run_shot_ids or [])) or 1,
            n_mouth - cut,
            n_mouth,
            [round(v) for v in bbox_list[0]],
        )

        # ---- clip loop (student; motion chained via latents) ------------
        is_student = True
        # student_first_clip_padding default in TBDub inference.py: the first
        # clip prerolls MOTION_NUM_FRAMES of frozen reference so the motion
        # latents always have history.
        first_clip_preroll = True
        stride = clip_num - motion_num
        total_length = get_total_length(
            audio_path, clip_num_frames=clip_num, motion_num_frames=motion_num
        )
        audio_length = get_audio_length(audio_path)
        real_length = min(audio_length, total_length)
        if real_length <= 0:
            raise ValueError(f"run audio has no usable frames: {audio_length}")

        if first_clip_preroll:
            num_clips = max(1, (real_length + stride - 1) // stride)
            required_video_length = num_clips * stride
        else:
            num_clips = 1 + max(0, total_length - clip_num) // stride
            required_video_length = total_length

        pingpong = make_pingpong_indices(len(reference_video), required_video_length)
        reference_video = [reference_video[i] for i in pingpong]
        model_reference_video = (
            [reference_video[0]] * motion_num + reference_video
            if first_clip_preroll
            else reference_video
        )

        motion_video = model_reference_video[:motion_num] if first_clip_preroll else None
        motion_latents = None
        hubert_features = None
        latent_segments = []
        clip_start = 0

        for clip_index in range(num_clips):
            audio_start = clip_start - motion_num if first_clip_preroll else clip_start
            clip_seed = self.seed + clip_index if is_student else self.seed
            logger.info(
                "TBDub clip %d/%d: start_frame=%d, audio_start=%d, seed=%d",
                clip_index + 1,
                num_clips,
                clip_start,
                audio_start,
                clip_seed,
            )
            reference_clip = model_reference_video[clip_start : clip_start + clip_num]
            generated_clip, outputs = self._pipeline(
                ref_video=reference_clip,
                start_idx=audio_start,
                audio_npy_path=None,
                audio_wav_path=audio_path,
                hubert_feat=hubert_features,
                per_chunk_audio=False,
                prompt="",
                prompt_emb=self._prompt_embedding,
                motion_video=motion_video,
                motion_latents=motion_latents,
                height=512,
                width=512,
                num_frames=clip_num,
                motion_latents_num_frames=motion_latent_num,
                ref_cfg_scale=self.ref_cfg_scale,
                audio_cfg_scale=self.audio_cfg_scale,
                num_inference_steps=self.num_student_steps,
                sigma_shift=self.sigma_shift,
                seed=clip_seed,
                use_dynamic_cfg=not is_student,
                cfg_merge=not is_student,
                replace_border_latents=True,
                replace_border_latents_width=1,
                replace_border_each_step=not is_student,
                decode_output=not self.motion_from_latents,
            )
            if hubert_features is None:
                hubert_features = outputs.get("hubert_feat")
            output_latents = outputs["latents"]

            if self.motion_from_latents:
                motion_video = None
                motion_latents = output_latents[:, :, -motion_latent_num:].clone()
            else:
                generated_clip = color_correction_lab(generated_clip, reference_clip)
                motion_video = generated_clip[-motion_num:]

            if clip_index == 0:
                latent_segments.append(output_latents)
            else:
                latent_segments.append(output_latents[:, :, motion_latent_num:])
            clip_start += stride

        output_latents = torch.cat(latent_segments, dim=2)
        self._pipeline.load_models_to_device(["vae"])
        decoded = self._pipeline.vae.decode(
            output_latents,
            device=self._pipeline.device,
            tiled=False,
            tile_size=(32, 32),
            tile_stride=(16, 16),
        )
        generated_video = self._pipeline.vae_output_to_video(decoded)
        if first_clip_preroll:
            generated_video = generated_video[motion_num:]
        generated_video = generated_video[:real_length]
        generated_video = color_correction_lab(
            generated_video, reference_video[:real_length]
        )

        # ---- paste back at TBDub-native fps ------------------------------
        # Debug hook: dump [plate crop | generated crop] side by side with the run
        # audio, so "the mouth does not follow the dub" can be attributed either to
        # the generator (columns match each other) or to our composite (they differ
        # but the output still shows the plate). Env: MUSETALK_TBDUB_CROP_DUMP=DIR
        dump_dir = os.environ.get("MUSETALK_TBDUB_CROP_DUMP", "").strip()
        if dump_dir:
            from video_utils import (  # TBDub repo
                concat_pil_videos_horizontally,
                save_video_with_audio,
            )

            self._crop_dump_index += 1
            stem = "crop_%03d_src%ds" % (
                self._crop_dump_index,
                int(round(len(raw_video) / self.target_fps)),
            )
            save_video_with_audio(
                concat_pil_videos_horizontally(
                    reference_video[:real_length], generated_video
                ),
                stem,
                dump_dir,
                audio_path=audio_path,
            )
            logger.info("[tbdub] crop comparison dumped: %s/%s.mp4", dump_dir, stem)

        blended = blend_crop_video_with_ref(
            generated_video,
            reference_video[:real_length],
            replace_border_latents_width=1,
        )
        pasted = paste_video_back(
            blended, raw_video[: len(blended)], bbox_list[: len(blended)]
        )
        if not pasted:
            return []

        # ---- re-time TBDub-native output onto the source-fps timeline ----
        # Generated frame j covers time j/25; source frame k covers k/fps.
        # Duplicated native-fps frames carried on the source timeline reproduce
        # the TBDub-native cadence (identical to delivering a 25fps video).
        out_frames: List[np.ndarray] = []
        for k in range(n_src):
            j = min(len(pasted) - 1, max(0, int(round(k * self.target_fps / fps))))
            rgb = np.asarray(pasted[j].convert("RGB"), dtype=np.uint8)
            out_frames.append(cv2.cvtColor(rgb, cv2.COLOR_RGB2BGR))
        return out_frames
